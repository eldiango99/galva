let CURRENT_LANG = localStorage.getItem('galva_lang') || 'fr';

function t(key){
  return (I18N[CURRENT_LANG] && I18N[CURRENT_LANG][key]) || (I18N.fr[key]) || key;
}

function setLang(lang){
  CURRENT_LANG = lang;
  localStorage.setItem('galva_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}
